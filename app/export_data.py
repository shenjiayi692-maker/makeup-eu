#!/usr/bin/env python3
"""Export data/cosmetics_reg.sqlite to app/data.js for the lookup page.

  python app/export_data.py

The page loads data.js with a plain <script> tag, so it also works when
index.html is opened straight from disk (file://), where fetch() is blocked.
Output is deterministic: same database in, same bytes out.
"""
import json
import os
import re
import sqlite3

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = os.environ.get('CELEX_DB') or os.path.join(ROOT, 'data', 'cosmetics_reg.sqlite')
OUT = os.path.join(ROOT, 'app', 'data.js')

FOOTNOTE_REF = re.compile(r'\(\s*(\d{1,2})\s*\)')
LABEL_START = re.compile(r'^(\([a-z]{1,2}\)|\([ivx]+\)|[a-z]\)|[-–•])\s', re.I)


def flat(text):
    """Join the PDF's column-wrapped lines back into running text.

    A line ending in '-' is a chemical-name break ('3,7-' + 'dimethyl'), so it
    joins without a space. A line that starts with a tier label such as '(b)'
    keeps its own line. Everything else joins with a single space.
    """
    if not text:
        return ''
    out = ''
    for line in str(text).split('\n'):
        line = line.strip()
        if not line:
            continue
        if not out:
            out = line
        elif LABEL_START.match(line):
            out += '\n' + line
        elif out.endswith('-') and not out.endswith(' -'):
            out += line
        else:
            out += ' ' + line
    return out


def main():
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row

    reviews = {}
    rf = os.path.join(os.path.dirname(DB), 'review_decisions.csv')
    if os.path.exists(rf):
        import csv
        with open(rf, encoding='utf-8') as f:
            reviews = {(r['annex'], r['ref_no']): r['reviewed_on'] for r in csv.DictReader(f)}

    foot = {}
    for r in con.execute('SELECT annex, marker, text, amended_by FROM footnotes'):
        foot.setdefault(r['annex'], {})[r['marker']] = flat(r['text'])

    subs = {}
    for r in con.execute('SELECT * FROM substances ORDER BY annex, entry_seq, seq'):
        subs.setdefault((r['annex'], r['entry_seq']), []).append({
            'ci': r['colour_index'] or '',
            'inci': flat(r['inci_name']),
            'cas': flat(r['cas']),
            'ec': flat(r['ec']),
            'ok': r['split_ok'],
        })

    conds = {}
    for r in con.execute('SELECT * FROM conditions ORDER BY annex, entry_seq, tier_seq'):
        conds.setdefault((r['annex'], r['entry_seq']), []).append({
            'n': r['tier_seq'],
            'tier': r['tier'] or '',
            'pt': flat(r['product_type']),
            'max': flat(r['max_concentration']),
            'val': r['max_conc_value'],
            'unit': r['max_conc_unit'] or '',
            'basis': r['max_conc_basis'] or '',
            'multi': json.loads(r['all_conc_values']) if r['all_conc_values'] else None,
            'other': flat(r['other']),
            'warn': flat(r['wording']),
        })

    entries = []
    order = "CASE annex WHEN 'II' THEN 0 WHEN 'III' THEN 1 WHEN 'IV' THEN 2 WHEN 'V' THEN 3 ELSE 4 END"
    for r in con.execute('SELECT * FROM entries ORDER BY %s, entry_seq' % order):
        key = (r['annex'], r['entry_seq'])
        cs = conds.get(key, [])
        texts = [r['chemical_name'], r['inci_name'], r['max_concentration'],
                 r['other'], r['wording']]
        for c in cs:
            texts += [c['max'], c['other'], c['warn']]
        markers = sorted({m for t in texts if t for m in FOOTNOTE_REF.findall(t)}, key=int)
        fns = [[m, foot[r['annex']][m]] for m in markers if m in foot.get(r['annex'], {})]
        entries.append({
            'a': r['annex'],
            'ref': r['ref_no'] or '',
            'st': r['status'],
            'amd': r['amended_by'] or '',
            'pg': [int(p) for p in (r['pages'] or '').split(',') if p.strip().isdigit()],
            'chem': flat(r['chemical_name']),
            'inci': flat(r['inci_name']),
            'ci': r['colour_index'] or '',
            'cas': flat(r['cas']),
            'ec': flat(r['ec']),
            'colour': r['colour'] or '',
            'rev': r['needs_review'],
            'revd': reviews.get((r['annex'], r['ref_no']), ''),
            'subs': subs.get(key, []),
            'conds': cs,
            'fn': fns,
        })

    payload = {
        'source': '02009R1223 — EN — 18.05.2026 — 041.001',
        'celex': '02009R1223-20260518',
        'entries': entries,
    }
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Generated by app/export_data.py from data/cosmetics_reg.sqlite. Do not edit.\n')
        f.write('window.COSMETICS_DATA = ')
        json.dump(payload, f, ensure_ascii=False, separators=(',', ':'))
        f.write(';\n')
    print('wrote %s: %d entries, %d bytes' % (OUT, len(entries), os.path.getsize(OUT)))


if __name__ == '__main__':
    main()


